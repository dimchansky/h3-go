func renderPlatform(b *strings.Builder, r result) {
	pureWins, uberWins, tied := timeWins(r)
	fmt.Fprintf(b, "\n## %s · `%s/%s`\n\n", platformTitle(r), r.goos, r.goarch)
	fmt.Fprintf(b, "%s; `%s`; %s. Across all scenarios: **this library %d wins**, **uber/h3-go %d wins**, %d no clear difference.\n\n",
		r.meta["go_version"], r.cpu, r.meta["cc"], pureWins, uberWins, tied)

	b.WriteString("### Execution time\n\n")
	b.WriteString("| Scenario | What it measures | this library | uber/h3-go v4.4.1 | advantage |\n")
	b.WriteString("|---|---|---:|---:|---:|\n")
	for _, scenario := range scenarios {
		m := r.metrics[scenario.name]["sec/op"]
		outcome := timeOutcome(m)
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			scenario.label,
			scenario.description,
			formatTimedMeasurement(m.pure, outcome > 0),
			formatTimedMeasurement(m.uber, outcome < 0),
			formatTimeAdvantage(m),
		)
	}

	b.WriteString("\n### Go heap\n\n")
	b.WriteString("These are Go benchmark allocation metrics, not total process memory.\n\n")
	b.WriteString("| Scenario | this library B/op | uber B/op | memory advantage | this library allocs/op | uber allocs/op | allocation advantage |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|\n")
	for _, scenario := range scenarios {
		bytes := r.metrics[scenario.name]["B/op"]
		allocs := r.metrics[scenario.name]["allocs/op"]
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s |\n",
			scenario.label,
			formatLower(bytes.pure.value, bytes.uber.value, formatBytes),
			formatLower(bytes.uber.value, bytes.pure.value, formatBytes),
			formatResourceAdvantage(bytes.pure.value, bytes.uber.value),
			formatLower(allocs.pure.value, allocs.uber.value, formatAllocs),
			formatLower(allocs.uber.value, allocs.pure.value, formatAllocs),
			formatResourceAdvantage(allocs.pure.value, allocs.uber.value),
		)
	}

	b.WriteString("\n### Process-level memory\n\n")
	fmt.Fprintf(b, "Each workload runs in an isolated process for %s iterations. Peak RSS includes\n", r.meta["memprobe_iters"])
	b.WriteString("Go and C memory; retained Go heap is sampled after forced garbage collection.\n")
	b.WriteString("Lower is better, but small RSS differences can reflect runtime/process noise.\n\n")
	b.WriteString("| Workload | What it measures | this library peak RSS | uber peak RSS | RSS advantage | this library retained Go heap | uber retained Go heap | heap advantage |\n")
	b.WriteString("|---|---|---:|---:|---:|---:|---:|---:|\n")
	for _, scenario := range memoryScenarios {
		m := r.memory[scenario.name]
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
			scenario.label,
			scenario.description,
			formatLower(m.pure.peakRSSKB, m.uber.peakRSSKB, formatKiB),
			formatLower(m.uber.peakRSSKB, m.pure.peakRSSKB, formatKiB),
			formatResourceAdvantage(m.pure.peakRSSKB, m.uber.peakRSSKB),
			formatLower(m.pure.heapAllocKB, m.uber.heapAllocKB, formatKiB),
			formatLower(m.uber.heapAllocKB, m.pure.heapAllocKB, formatKiB),
			formatResourceAdvantage(m.pure.heapAllocKB, m.uber.heapAllocKB),
		)
	}
	b.WriteString("\nThe raw process-memory matrix also records wall time, cumulative allocation,\n")
	b.WriteString("Go runtime system memory, malloc count, garbage collections, and checksums.\n")

	b.WriteString("\n### Reusable-buffer modes\n\n")
	b.WriteString("Collection APIs are also measured as `pure-cold` (an `Append*` call with a nil\n")
	b.WriteString("destination) and `pure-warm` (the destination buffer is reused). These rows\n")
	b.WriteString("compare those modes with this library's convenience API; the cgo binding has no\n")
	b.WriteString("equivalent caller-owned-buffer mode.\n\n")
	b.WriteString("| Scenario | convenience time | cold time | warm time | warm time change | B/op convenience → warm | allocs/op convenience → warm |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|\n")
	for _, scenario := range scenarios {
		timeMetric := r.metrics[scenario.name]["sec/op"]
		if !timeMetric.warm.present {
			continue
		}
		bytes := r.metrics[scenario.name]["B/op"]
		allocs := r.metrics[scenario.name]["allocs/op"]
		outcome := warmOutcome(timeMetric)
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s | %s | %s |\n",
			scenario.label,
			formatTimedMeasurement(timeMetric.pure, outcome < 0),
			formatOptionalTime(timeMetric.cold),
			formatTimedMeasurement(timeMetric.warm, outcome > 0),
			formatWarmAdvantage(timeMetric),
			formatTransition(bytes.pure.value, bytes.warm.value, formatBytes),
			formatTransition(allocs.pure.value, allocs.warm.value, formatAllocs),
		)
	}

	fmt.Fprintf(b, "\n<details>\n<summary>Run provenance and raw artifacts</summary>\n\n")
	fmt.Fprintf(b, "- Run: `%s`; repository: `%s`; flags: `%s`\n", r.meta["date_utc"], shortCommit(r.meta["repo_commit"]), r.meta["bench_flags"])
	fmt.Fprintf(b, "- Implementations: `%s`; pure-Go target: %s\n", r.meta["uber_h3_go"], r.meta["pure_go_h3_target"])
	fmt.Fprintf(b, "- Environment note: %s\n", r.meta["environment"])
	fmt.Fprintf(b, "- [Metadata](%s/metadata.txt) · [full benchstat table](%s/benchstat.txt) · [raw output](%s/bench-raw.txt) · [process memory matrix](%s/memory.tsv)\n",
		r.dir, r.dir, r.dir, r.dir)
	b.WriteString("\n</details>\n")
}

// timeOutcome returns 1 when pure is significantly faster, -1 when uber is,
// and 0 when benchstat reports no clear difference.
func timeOutcome(m metric) int {
	if m.uber.delta == "~" {
		return 0
	}
	if m.uber.value > m.pure.value {
		return 1
	}
	return -1
}

func timeWins(r result) (pure, uber, tied int) {
	for _, scenario := range scenarios {
		switch timeOutcome(r.metrics[scenario.name]["sec/op"]) {
		case 1:
			pure++
		case -1:
			uber++
		default:
			tied++
		}
	}
	return pure, uber, tied
}

func warmOutcome(m metric) int {
	if m.warm.delta == "~" {
		return 0
	}
	if m.warm.value < m.pure.value {
		return 1
	}
	return -1
}

func formatTimedMeasurement(m measurement, bold bool) string {
	value := formatTime(m.value)
	if bold {
		value = "**" + value + "**"
	}
	if m.ci != "" {
		value += " ±" + m.ci
	}
	return value
}

func formatOptionalTime(m measurement) string {
	if !m.present {
		return "—"
	}
	return formatTimedMeasurement(m, false)
}

func formatTimeAdvantage(m metric) string {
	if m.uber.delta == "~" {
		return "⚪ ~ (" + rawWinner(m.pure.value, m.uber.value, "this library", "uber") + ")"
	}
	if m.uber.value > m.pure.value {
		return "🟢 " + normalizeSignedPercent(m.uber.delta)
	}
	return "🔴 " + normalizeSignedPercent(m.uber.delta)
}

func formatWarmAdvantage(m metric) string {
	if m.warm.delta == "~" {
		return "⚪ ~ (" + rawWinner(m.pure.value, m.warm.value, "convenience", "warm") + ")"
	}
	change := rawAdvantage(m.warm.value, m.pure.value)
	if m.warm.value < m.pure.value {
		return fmt.Sprintf("🟢 +%.2f%% faster", change)
	}
	return fmt.Sprintf("🔴 −%.2f%% slower", -change)
}

func rawWinner(first, second float64, firstName, secondName string) string {
	if first == second {
		return "same raw median"
	}
	if first < second {
		return fmt.Sprintf("%s %.2f%% faster raw", firstName, (second/first-1)*100)
	}
	return fmt.Sprintf("%s %.2f%% faster raw", secondName, (first/second-1)*100)
}

func formatResourceAdvantage(pure, uber float64) string {
	switch {
	case pure == uber:
		return "⚪ same"
	case pure == 0:
		return "🟢 zero"
	case uber == 0:
		return "🔴 uber is zero"
	case pure < uber:
		return "🟢 " + signedPercent(rawAdvantage(pure, uber))
	default:
		return "🔴 " + signedPercent(rawAdvantage(pure, uber))
	}
}

func formatLower(value, other float64, format func(float64) string) string {
	result := format(value)
	if value < other {
		return "**" + result + "**"
	}
	return result
}

func formatTransition(pure, warm float64, format func(float64) string) string {
	left, right := format(pure), format(warm)
	if pure < warm {
		left = "**" + left + "**"
	} else if warm < pure {
		right = "**" + right + "**"
	}
	return left + " → " + right
}

func rawAdvantage(pure, other float64) float64 {
	return (other/pure - 1) * 100
}

func normalizeSignedPercent(value string) string {
	return strings.ReplaceAll(value, "-", "−")
}

func signedPercent(value float64) string {
	if value > 0 && value < 0.005 {
		return "+<0.01%"
	}
	if value < 0 && value > -0.005 {
		return "−<0.01%"
	}
	if value == 0 {
		return "0.00%"
	}
	if value > 0 {
		return fmt.Sprintf("+%.2f%%", value)
	}
	return fmt.Sprintf("−%.2f%%", math.Abs(value))
}

func formatTime(seconds float64) string {
	switch {
	case seconds >= 1:
		return formatScaled(seconds) + " s"
	case seconds >= 1e-3:
		return formatScaled(seconds*1e3) + " ms"
	case seconds >= 1e-6:
		return formatScaled(seconds*1e6) + " µs"
	default:
		return formatScaled(seconds*1e9) + " ns"
	}
}

func formatScaled(value float64) string {
	decimals := 0
	switch {
	case value < 10:
		decimals = 3
	case value < 100:
		decimals = 2
	case value < 1000:
		decimals = 1
	}
	return strconv.FormatFloat(value, 'f', decimals, 64)
}

func formatBytes(value float64) string {
	if value < 1024 {
		return fmt.Sprintf("%.0f B", value)
	}
	if value < 1024*1024 {
		return formatDataScaled(value/1024) + " KiB"
	}
	return formatDataScaled(value/(1024*1024)) + " MiB"
}

func formatKiB(value float64) string {
	return formatBytes(value * 1024)
}

func formatDataScaled(value float64) string {
	if math.Trunc(value) == value {
		return strconv.FormatFloat(value, 'f', 0, 64)
	}
	return strconv.FormatFloat(value, 'f', 3, 64)
}

func formatAllocs(value float64) string {
	return strconv.FormatFloat(value, 'f', -1, 64)
}
