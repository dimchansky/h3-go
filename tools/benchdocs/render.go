func renderREADME(results []result) string {
	var b strings.Builder
	b.WriteString(readmeBegin)
	b.WriteString("\n\nThe complete report covers **all 33 scenarios**; this scorecard counts the\n")
	b.WriteString("statistically faster implementation for each execution-time result.\n\n")
	b.WriteString("| Environment | this library faster | uber/h3-go faster | no clear difference |\n")
	b.WriteString("|---|---:|---:|---:|\n")
	for _, r := range results {
		pure, uber, tied := timeWins(r)
		fmt.Fprintf(&b, "| %s · `%s/%s` | **%d** | **%d** | %d |\n", platformTitle(r), r.goos, r.goarch, pure, uber, tied)
	}
	b.WriteString("\n**[Explore every scenario, timing, allocation, process-memory, and reusable-buffer result →](docs/benchmarks/results.md)**\n\n")
	b.WriteString("Several outcomes reverse between the two environments. That is a measured\n")
	b.WriteString("platform difference, not evidence that either implementation is universally\n")
	b.WriteString("faster; absolute timings must not be compared across machines.\n")
	b.WriteString(readmeEnd)
	return b.String()
}

